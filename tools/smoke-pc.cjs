  for (const [k, label] of [['2', '공구 강화'], ['3', '상자'], ['4', '도감'], ['1', '서비스']]) {
    await page.keyboard.press(k);
    await page.waitForTimeout(150);
    check(`${k}키 → ${label} 탭`, (await page.locator('.dock .tab.active').innerText()).includes(label));
  }
  await page.keyboard.press('w');
  check('W → x10', (await page.locator('.seg .chip.active').innerText()) === 'x10');
  await page.keyboard.press('e');
  check('E → MAX', (await page.locator('.seg .chip.active').innerText()) === 'MAX');
  await page.keyboard.press('q');
  check('Q → x1', (await page.locator('.seg .chip.active').innerText()) === 'x1');
  await page.locator('button[aria-label="설정"]').click();
  await page.waitForSelector('.overlay');
  const m0 = (await gs(page)).stats?.totalTaps ?? 0;
  await page.keyboard.press('Escape');
  await page.waitForTimeout(150);
  check('Esc로 모달이 닫힌다', (await page.locator('.overlay').count()) === 0);
  await page.locator('button[aria-label="설정"]').click();
  await page.waitForSelector('.overlay');
  await page.evaluate(() => document.activeElement && document.activeElement.blur());
  await page.keyboard.press('Space');
  await page.keyboard.press('2');
  await page.waitForTimeout(150);
  check('모달 중 Space·숫자는 전화·탭 전환을 하지 않는다', ((await gs(page)).stats?.totalTaps ?? 0) === m0 && (await page.locator('.dock .tab.active').innerText()).includes('서비스'));
  await page.keyboard.press('Escape');
