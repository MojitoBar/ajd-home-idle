    check('공개(PC): 새 게임은 탭이 서비스뿐', tabsShown === 1, String(tabsShown));
    const gone = await p2.evaluate(() => ['.move-block', '.slots-pill', '.bundle-toggle', '.speed-wrap .info-btn', '.top .badge', '.perk-btn', '.strat-top'].filter((q) => document.querySelector(q)?.getBoundingClientRect().width > 0));
    check('공개(PC): 새 게임에서 이사 줄·약정 칸·결합·i·영구 칩·특전 버튼이 숨겨져 있다', gone.length === 0, gone.join(','));
    await p2.screenshot({ path: path.join(__dirname, '..', 'screenshots', 'unlock', 'pc-new-game.png') });
